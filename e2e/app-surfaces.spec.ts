import { expect, test } from 'playwright/test'
import { getDB } from '../lib/drills'

test('library search, answer reveal, study selection, and mobile navigation work together', async ({ page }) => {
  const errors: string[] = []
  page.on('pageerror', error => errors.push(error.message))
  await page.setViewportSize({ width: 1440, height: 1000 })
  await page.goto('/library')
  await expect(page.getByRole('heading', { name: 'Your library.' })).toBeVisible()
  await expect(page.getByRole('status')).toHaveCount(0)
  await page.getByLabel('Language', { exact: true }).selectOption('fr')
  await expect(page.getByLabel('Language', { exact: true })).toHaveValue('fr')
  const item = getDB('fr')[0]
  await page.getByRole('searchbox').fill(item.prompt)
  const exercise = page.locator('.product-exercise-list details').filter({ hasText: item.prompt }).first()
  await exercise.locator('summary').click()
  await expect(exercise.locator('.product-answer')).toContainText(item.answer)
  await page.getByRole('searchbox').fill('unmatched-search-93847')
  await expect(page.getByRole('heading', { name: 'No matching exercises' })).toBeVisible()
  await page.getByRole('searchbox').fill('')
  await page.screenshot({ path: '/tmp/linguaflow-library-desktop.png', fullPage: false })
  await page.getByRole('navigation').getByRole('link', { name: 'Study', exact: true }).click()
  await page.getByLabel('Language', { exact: true }).selectOption('fr')
  await expect(page.getByLabel('Language', { exact: true })).toHaveValue('fr')
  await page.getByRole('searchbox').fill(item.prompt)
  await page.locator('.product-study-list input').first().check()
  await page.screenshot({ path: '/tmp/linguaflow-study-desktop.png', fullPage: false })
  await page.getByRole('button', { name: 'Study selected' }).click()
  await expect(page.locator('.study-scene')).toContainText(item.prompt)
  await page.getByRole('button', { name: 'Show answer', exact: true }).click()
  await expect(page.locator('.study-inner')).toHaveClass(/flipped/)
  await page.getByLabel('Playback speed').selectOption('0.75')
  await page.setViewportSize({ width: 390, height: 844 })
  for (const [label, path] of [['Practice', 'drill'], ['Library', 'library'], ['Study', 'study'], ['Today', 'today'], ['Progress', 'dashboard'], ['Settings', 'settings']]) {
    await page.getByRole('navigation').getByRole('link', { name: label, exact: true }).click()
    await expect(page).toHaveURL(new RegExp(`/${path}$`))
    await expect(page.getByRole('heading', { level: 1 })).toBeVisible()
    expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), `${label} fits on mobile`).toBe(true)
    await page.screenshot({ path: `/tmp/linguaflow-${path}-mobile-refined.png`, fullPage: false })
  }
  expect(errors).toEqual([])
})

test('saved exercises stay available without taking over built-in practice', async ({ page }) => {
  await page.goto('/today')
  await page.evaluate(() => localStorage.setItem('linguaflow_demo_custom_list', JSON.stringify([{ id: 'saved-example', type: 'translation', instruction: 'Translate to Spanish.', prompt: 'The blue notebook.', answer: 'El cuaderno azul.', promptLang: 'en-US' }])))
  await page.goto('/drill?type=phrase&language=es')
  await expect(page.getByLabel('Material', { exact: true })).toHaveValue('built-in')
  await page.setViewportSize({ width: 1440, height: 1000 })
  await page.screenshot({ path: '/tmp/linguaflow-practice-desktop.png', fullPage: false })
  await page.getByTestId('begin-session').click()
  await expect(page.getByTestId('drill-prompt')).toBeVisible()
  await page.screenshot({ path: '/tmp/linguaflow-drill-desktop.png', fullPage: false })
  await page.goto('/drill?source=custom')
  await expect(page.getByRole('heading', { name: 'Custom list' })).toBeVisible()
  await expect(page.getByText('AI Model', { exact: true })).toHaveCount(0)
  await page.getByRole('button', { name: 'Upload File' }).click()
  await expect(page.getByText('1 item', { exact: true })).toBeVisible()
  await page.getByRole('button', { name: 'Close exercise editor' }).click()
  await page.getByTestId('begin-session').click()
  await expect(page.getByTestId('drill-prompt')).toHaveText('The blue notebook.')
  await page.goto('/drill?type=custom')
  await page.getByLabel('Material', { exact: true }).selectOption('built-in')
  await page.getByTestId('begin-session').click()
  await expect(page.getByTestId('drill-prompt')).toBeVisible()
  await expect(page.getByTestId('drill-prompt')).not.toHaveText('The blue notebook.')
})
