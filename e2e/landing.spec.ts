import { expect, test } from 'playwright/test'

test('public landing gives visitors an honest exercise and a clear entry into practice', async ({ page }) => {
  const errors: string[] = []
  page.on('pageerror', error => errors.push(error.message))
  await page.setViewportSize({ width: 1440, height: 1000 })
  await page.goto('/welcome')
  await expect(page).toHaveTitle('LinguaFlow — Practice the sentences you need.')
  await expect(page.getByRole('heading', { name: 'Practice the sentences you need.' })).toBeVisible()
  await expect(page.getByRole('navigation')).not.toContainText('Settings')
  await expect(page.getByText('87%', { exact: true })).toHaveCount(0)
  await expect(page.getByText('13s', { exact: true })).toHaveCount(0)
  const form = page.getByRole('form', { name: 'Example English exercise' })
  await expect(form.getByLabel('Your answer')).toHaveValue('')
  await expect(form.getByRole('button', { name: 'Check answer' })).toBeDisabled()
  await page.screenshot({ path: '/tmp/linguaflow-landing-refined-desktop.png', fullPage: true })
  await form.getByLabel('Your answer').fill('Where is the hotel?')
  await form.getByLabel('Your answer').press('Enter')
  await expect(form.getByRole('status')).toContainText('Compare your answer.')
  await form.getByLabel('Your answer').fill("She doesn't work from home.")
  await form.getByLabel('Your answer').press('Enter')
  await expect(form.getByRole('status')).toContainText('Correct.')
  await form.getByLabel('Your answer').fill('')
  await form.getByRole('button', { name: 'Show answer' }).click()
  await expect(form.getByRole('status')).toContainText('One way to say it:')
  await page.getByRole('link', { name: 'How it works' }).click()
  await expect(page.getByRole('heading', { name: 'Make each session count.' })).toBeInViewport()
  await page.getByRole('link', { name: 'Start practicing' }).click()
  await expect(page).toHaveURL(/\/drill\?language=en&type=mixed&count=5$/)
  await expect(page.getByRole('heading', { name: 'Begin practice.' })).toBeVisible()
  await expect(page.getByLabel('Language', { exact: true })).toHaveValue('en')
  await expect(page.getByRole('navigation')).toContainText('Practice')
  await page.goto('/welcome')
  await page.setViewportSize({ width: 390, height: 844 })
  await expect(form).toBeVisible()
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
  await page.screenshot({ path: '/tmp/linguaflow-landing-refined-mobile.png', fullPage: true })
  expect(errors).toEqual([])
})
